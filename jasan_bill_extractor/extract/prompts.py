def build_user_prompt(filename_hint: str, frame_index: int, frame_count: int) -> str:
    return (
        f"파일명: {filename_hint} (페이지 {frame_index + 1}/{frame_count})\n"
        "이 이미지에서 청구서 정보를 추출해 record_extracted_bills 도구로 반환하세요."
    )
